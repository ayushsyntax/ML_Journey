    "    ax.set_ylabel(\"Feature 2\")\n",
    "    plot_area = st.pyplot(fig)\n",
    "\n",
    "    st.success(f\"Model Accuracy: **{round(accuracy_score(y_test, y_pred), 2)}**\")\n"
