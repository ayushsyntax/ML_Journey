    "import matplotlib.pyplot as plt\n",
    "import streamlit as st\n",
    "import numpy as np\n",
    "from sklearn.model_selection import train_test_split\n",
    "from sklearn.datasets import make_blobs\n",
    "from sklearn.linear_model import LogisticRegression\n",
    "from sklearn.metrics import accuracy_score\n",
    "\n",
    "# Load dataset and plot\n",
    "def load_initial_graph(dataset, ax):\n",
    "    if dataset == \"Binary\":\n",
    "        X, y = make_blobs(n_features=2, centers=2, random_state=6)\n",
    "    elif dataset == \"Multiclass\":\n",
    "        X, y = make_blobs(n_features=2, centers=3, random_state=2)\n",
    "    ax.scatter(X[:, 0], X[:, 1], c=y, cmap='rainbow')\n",
    "    return X, y\n",
    "\n",
    "# Draw decision boundary grid\n",
    "def draw_meshgrid(X):\n",
    "    a = np.arange(start=X[:, 0].min() - 1, stop=X[:, 0].max() + 1, step=0.01)\n",
    "    b = np.arange(start=X[:, 1].min() - 1, stop=X[:, 1].max() + 1, step=0.01)\n",
    "    XX, YY = np.meshgrid(a, b)\n",
    "    input_array = np.c_[XX.ravel(), YY.ravel()]\n",
    "    return XX, YY, input_array\n",
    "\n",
    "# Streamlit UI\n",
    "st.sidebar.markdown(\"# Logistic Regression Classifier\")\n",
    "\n",
    "dataset = st.sidebar.selectbox(\"Select Dataset\", (\"Binary\", \"Multiclass\"))\n",
    "penalty = st.sidebar.selectbox(\"Regularization\", (\"l2\", \"l1\", \"elasticnet\", \"none\"))\n",
    "C = st.sidebar.number_input(\"C (Regularization strength)\", value=1.0)\n",
    "solver = st.sidebar.selectbox(\"Solver\", (\"newton-cg\", \"lbfgs\", \"liblinear\", \"sag\", \"saga\"))\n",
    "max_iter = st.sidebar.number_input(\"Max Iterations\", value=100, step=10)\n",
    "multi_class = st.sidebar.selectbox(\"Multi Class\", (\"auto\", \"ovr\", \"multinomial\"))\n",
    "\n",
    "# l1_ratio is only used when penalty='elasticnet' and solver='saga'\n",
    "l1_ratio = None\n",
    "if penalty == 'elasticnet' and solver == 'saga':\n",
    "    l1_ratio = st.sidebar.slider(\"l1 Ratio (only for elasticnet)\", 0.0, 1.0, 0.5)\n",
    "\n",
    "# Plot original dataset\n",
    "plt.style.use('fivethirtyeight')\n",
    "fig, ax = plt.subplots()\n",
    "X, y = load_initial_graph(dataset, ax)\n",
    "X_train, X_test, y_train, y_test = train_test_split(X, y, random_state=42)\n",
    "plot_area = st.pyplot(fig)\n",
    "\n",
    "# Run algorithm\n",
    "if st.sidebar.button(\"Run Algorithm\"):\n",
    "    plot_area.empty()\n",
    "\n",
    "    clf = LogisticRegression(\n",
    "        penalty=penalty,\n",
    "        C=C,\n",
    "        solver=solver,\n",
    "        max_iter=max_iter,\n",
    "        multi_class=multi_class,\n",
    "        l1_ratio=l1_ratio\n",
    "    )\n",
    "\n",
    "    clf.fit(X_train, y_train)\n",
    "    y_pred = clf.predict(X_test)\n",
    "\n",
    "    XX, YY, input_array = draw_meshgrid(X)\n",
    "    labels = clf.predict(input_array)\n",
    "\n",
    "    ax.contourf(XX, YY, labels.reshape(XX.shape), alpha=0.5, cmap='rainbow')\n",
